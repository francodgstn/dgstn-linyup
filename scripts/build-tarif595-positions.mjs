#!/usr/bin/env node
// Generates packages/shared/src/data/tarif595/positions.ts from positions.tsv —
// the Tarif 595 position list as published by Forum Datenaustausch (Referenzdaten,
// "Tarif 595 Ambulante gesundheitsfördernde Leistungen VVG"). The XLSX beside the
// TSV is the provenance copy of the download; the TSV is the exported `tariff`
// sheet reduced to the columns the app needs (type, chapter_no, service_no, the
// three descriptions, valid_from, valid_until). Interpretations are deliberately
// not shipped in this phase (they quadruple the payload).
//
// The list changes every 1 January. To update: download the new XLSX, re-export
// the TSV (scripts/lib has no XLSX reader on purpose — a yearly file does not
// earn a dependency), run `pnpm tarif595:positions`, and let
// packages/functions/src/tarif595/positions.test.ts tell you what moved.
//
// Refuses: duplicate service codes, a row missing any of the three languages,
// an unparsable date, an unknown row type.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(ROOT, 'packages/shared/src/data/tarif595')
const SRC = join(DIR, 'positions.tsv')
const OUT = join(DIR, 'positions.ts')

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/
/** The list uses 9998-12-31 / 2999-12-31 as "open-ended". */
const OPEN_ENDED = new Set(['9998-12-31', '2999-12-31', '9999-12-31'])

const lines = readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n').split('\n').filter((l) => l.length > 0)
const header = lines[0].split('\t')
const col = (name) => {
  const i = header.indexOf(name)
  if (i === -1) throw new Error(`positions.tsv: missing column ${name}`)
  return i
}
const C = {
  type: col('type'),
  chapter: col('chapter_no'),
  code: col('service_no'),
  de: col('description_de'),
  fr: col('description_fr'),
  it: col('description_it'),
  from: col('valid_from'),
  until: col('valid_until'),
}

const chapters = []
const positions = []
const seen = new Set()
for (const [n, line] of lines.slice(1).entries()) {
  const f = line.split('\t')
  const row = n + 2
  const type = f[C.type]
  const text = { de: f[C.de]?.trim(), fr: f[C.fr]?.trim(), it: f[C.it]?.trim() }
  for (const lang of ['de', 'fr', 'it']) {
    if (!text[lang]) throw new Error(`positions.tsv:${row}: missing ${lang} text`)
  }
  const from = f[C.from]?.trim()
  const until = f[C.until]?.trim()
  if (!DATE_RE.test(from) || !DATE_RE.test(until)) throw new Error(`positions.tsv:${row}: bad date`)
  const chapter = f[C.chapter]?.trim()
  if (type === 'chp') {
    chapters.push({ id: chapter, title: text })
  } else if (type === 'srv') {
    const code = f[C.code]?.trim()
    if (!/^[0-9]{4}$/.test(code)) throw new Error(`positions.tsv:${row}: bad code ${code}`)
    if (seen.has(code)) throw new Error(`positions.tsv:${row}: duplicate code ${code}`)
    seen.add(code)
    positions.push({ code, chapter, text, valid_from: from, valid_until: OPEN_ENDED.has(until) ? null : until })
  } else {
    throw new Error(`positions.tsv:${row}: unknown type ${type}`)
  }
}

const q = (s) => JSON.stringify(s)
const out = `// GENERATED by scripts/build-tarif595-positions.mjs from positions.tsv — do not edit.
// Source: Forum Datenaustausch, Referenzdaten, Tarif 595 "Ambulante gesundheitsfördernde
// Leistungen VVG" (the XLSX beside the TSV is the downloaded original). The
// descriptions are the OFFICIAL texts and must be printed unaltered (Helsana
// Wegleitung §1.3); only code 9999 may carry a studio's own text.
//
// This module is exposed on the \`@linyup/shared/tarif595-positions\` subpath and
// is NOT re-exported from index.ts: @linyup/shared is CommonJS, so anything on
// the index lands in every web page's vendor chunk. The counts that describe
// this table live in packages/functions/src/tarif595/positions.test.ts, where
// they are executable — never in a comment.

export interface Tarif595Position {
  code: string
  chapter: string
  text: { de: string; fr: string; it: string }
  /** YYYY-MM-DD */
  valid_from: string
  /** YYYY-MM-DD, or null when open-ended. */
  valid_until: string | null
}

export interface Tarif595Chapter {
  id: string
  title: { de: string; fr: string; it: string }
}

export const TARIF595_LIST_VERSION = ${q('2026-06-03')}

export const TARIF595_CHAPTERS: readonly Tarif595Chapter[] = [
${chapters.map((c) => `  { id: ${q(c.id)}, title: { de: ${q(c.title.de)}, fr: ${q(c.title.fr)}, it: ${q(c.title.it)} } },`).join('\n')}
]

export const TARIF595_POSITIONS: readonly Tarif595Position[] = [
${positions
  .map(
    (p) =>
      `  { code: ${q(p.code)}, chapter: ${q(p.chapter)}, text: { de: ${q(p.text.de)}, fr: ${q(p.text.fr)}, it: ${q(p.text.it)} }, valid_from: ${q(p.valid_from)}, valid_until: ${p.valid_until === null ? 'null' : q(p.valid_until)} },`
  )
  .join('\n')}
]

const BY_CODE: ReadonlyMap<string, Tarif595Position> = new Map(TARIF595_POSITIONS.map((p) => [p.code, p]))

/** The position by code, whatever its validity. */
export function tarif595Position(code: string): Tarif595Position | null {
  return BY_CODE.get(code) ?? null
}

/** The position by code IF it is valid on \`dateIso\` (YYYY-MM-DD) — the line
 *  date decides which edition of the list applies, because positions expire
 *  and appear each 1 January. */
export function tarif595PositionOn(code: string, dateIso: string): Tarif595Position | null {
  const p = BY_CODE.get(code)
  if (!p) return null
  if (dateIso < p.valid_from) return null
  if (p.valid_until !== null && dateIso > p.valid_until) return null
  return p
}

/** Every position valid on \`dateIso\`, in list order. */
export function tarif595PositionsOn(dateIso: string): Tarif595Position[] {
  return TARIF595_POSITIONS.filter((p) => dateIso >= p.valid_from && (p.valid_until === null || dateIso <= p.valid_until))
}
`
writeFileSync(OUT, out, 'utf8')
console.log(`tarif595 positions: ${positions.length} positions, ${chapters.length} chapters → ${OUT}`)
